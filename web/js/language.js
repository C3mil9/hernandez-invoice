// Use localized browser validation messages while keeping native input checks.
export function enableLocalizedValidation() {
  document.addEventListener(
    "invalid",
    (event) => {
      const field = event.target;
      if (typeof field.setCustomValidity !== "function") return;
      field.setCustomValidity("");
      if (language !== "es" || field.validity.valid) return;
      let message = "Please enter a valid value.";
      if (field.validity.valueMissing) message = "Please fill out this field.";
      else if (field.validity.typeMismatch && field.type === "email")
        message = "Please enter a valid email address.";
      else if (field.validity.rangeUnderflow || field.validity.rangeOverflow)
        message = "Please enter a value within the allowed range.";
      else if (field.validity.stepMismatch)
        message = "Please check the number of decimal places.";
      field.setCustomValidity(t(message));
    },
    true,
  );
  for (const eventName of ["input", "change"])
    document.addEventListener(
      eventName,
      (event) => {
        if (typeof event.target.setCustomValidity === "function")
          event.target.setCustomValidity("");
      },
      true,
    );
}
