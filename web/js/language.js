const storageKey = "hernandez-invoice-language";
let language = "en";
try {
  if (localStorage.getItem(storageKey) === "es") language = "es";
} catch {
  /* Keep the current session in English. */
}

export function currentLanguage() {
  return language;
}
export function setLanguage(value) {
  language = value === "es" ? "es" : "en";
  try {
    localStorage.setItem(storageKey, language);
  } catch {
    /* The switch still works for this session. */
  }
  document.documentElement.lang = language;
}
export function locale() {
  return language === "es" ? "es-US" : "en-US";
}
export function invoiceCount(count) {
  return language === "es"
    ? `${count} ${count === 1 ? "factura" : "facturas"}`
    : `${count} ${count === 1 ? "invoice" : "invoices"}`;
}
export function t(text, values = {}) {
  const result = language === "es" ? spanish[text] || text : text;
  return result.replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(values, key)
      ? String(values[key])
      : match,
  );
}
export function invoiceStatus(status) {
  return t(status);
}

